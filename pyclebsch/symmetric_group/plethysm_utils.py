"""
Internal helpers for su_n_operators.find_plethysms, which is adapted from
GroupMath (R. M. Fonseca, arXiv:2011.01764) and whose docstring defines
plethysms.

find_plethysms computes the plethysm V^(λ) of an irrep V by the formula on
p. 72 of the LiE manual (M. A. A. van Leeuwen et al.,
http://www-math.univ-poitiers.fr/~maavl/LiE/):

    V^(λ) = sum over ρ of (|C_ρ| / n!) χ_λ(ρ) ψ^(ρ_1)(V) x ψ^(ρ_2)(V) x ...,

summed over the partitions ρ of n, each listing the cycle lengths of one
class of permutations (defined below). These helpers supply its pieces:
- A permutation of n objects splits into disjoint cycles: groups of objects
  that it moves around in a loop, with an object it leaves alone counting
  as a cycle of length 1. For example, the permutation of 3 objects that
  swaps two and fixes one has cycles of lengths 2 and 1. A permutation's
  cycle lengths, sorted from longest, form a partition ρ of n ([2, 1] in
  the example; the literature calls ρ the permutation's cycle type). Two
  permutations are conjugate exactly when their cycle lengths agree, so
  each ρ labels a conjugacy class C_ρ. _class_order gives its size,
  |C_ρ| = n! / prod_k (k^(m_k) m_k!), where m_k is the number of cycles of
  length k. _class_character gives the character χ_λ(ρ) of the irrep λ of
  S_n on that class, by the Murnaghan-Nakayama rule (see the reference in
  tableaux._rim_hooks).
- The k-th Adams operator ψ^k multiplies each weight μ of a representation
  V by k, keeping its multiplicity. The weights kμ are those of a
  combination of irreps with integer coefficients, some of which can be
  negative, and ψ^k(V) is that combination. Equivalently, its character at
  g is V's character at g^k. For example, the SU(3) fundamental has weights
  μ_1, μ_2, μ_3, and ψ^2(3) = 6 - 3bar has weights 2μ_1, 2μ_2, 2μ_3: the 6
  has those and the μ_i + μ_j (i < j), which are the weights of the 3bar.
  _Adams computes ψ^k(V) from V's dominant weights.
- To write ψ^k(V) as a combination of irreps, _Adams uses two more helpers.
  _Weyl_orbit lists the weights that the Weyl group makes from one weight.
  For SU(N) the Weyl group permutes the N coefficients of a weight written
  as a combination of the N weights of the fundamental (equivalently, it is
  generated by the reflections in the hyperplanes orthogonal to the simple
  roots).
  _find_iweight gives the i-weight of the irrep with a given highest weight.

For example, with V the SU(3) fundamental and λ = [2, 1], the classes with
cycle lengths [1, 1, 1], [2, 1] and [3] (the identity, the 3 swaps and the
2 three-cycles) give
V^([2, 1]) = (1/6)[2 (3 x 3 x 3) + 0 - 2 ψ^3(3)] = 8.
"""

import numpy as np
from math import factorial
from collections import Counter, defaultdict
from pyclebsch.symmetric_group.tableaux import _rim_hooks

def _class_order(partition, n):
    """The number of permutations of n objects with the cycle lengths given
    by partition.
    """
    prod,cycle_tally = 1,Counter(partition)
    for cycle_len, num in cycle_tally.items():
        prod *= cycle_len**num * factorial(num)

    return round(factorial(n)/prod)


def _class_character(irrep_partition, cycle_lengths):
    """Computes, recursively, the character of the irrep of S_n labeled by
    irrep_partition on the permutations with the given cycle_lengths.
    """
    if len(irrep_partition)==0:
        return 1
    else:
        new_irreps = _rim_hooks(irrep_partition, cycle_lengths[0])
        remaining_cycle_lengths = cycle_lengths[1:]
        character = sum(
            (-1)**l * _class_character(p, remaining_cycle_lengths) for p, l in new_irreps
        )
        return character


def _find_iweight(zweight):
    """Finds the i-weight corresponding to a dominant weight,
    assumed to be the highest weight of an irrep.
    """
    pweight, count = [0],-1
    for i in range(len(zweight)-1,-1,-1):
        if i==len(zweight)-1:
            pweight.append(int(2*zweight[i]))
        else:
            pweight.append(int(2*zweight[i] + pweight[count+1]))
        count += 1

    return tuple(pweight[::-1])


def _Weyl_orbit(zweight, N, simple_roots):
    """Finds Weyl orbit of a given SU(N) z-weight.
    """

    orbit,weights = [np.array(zweight)],[np.array(zweight)]
    while len(weights) != 0:
        trial_weights,new_weights = [],[]
        for w in weights:
            if not np.any(w):
                trial_weights.append(None)
            else:
                reflections = []
                for i in range(N-1):
                    reflections.append(w - w[i]*simple_roots[i])
                trial_weights.append(reflections)
        for i in range(N-1):
            for j in range(len(weights)):
                if weights[j][i] <= 0 or trial_weights[j] is None:
                    continue
                else:
                    check = trial_weights[j][i][i+1:N-1]
                    if np.all(check==abs(check)):
                        new_weights.append(trial_weights[j][i])
                    else:
                        continue
        weights = new_weights
        if len(weights) != 0:
            orbit += weights
        else:
            continue

    return orbit


def _Adams(k, N, dominant_zweights, simple_roots):
    """Applies the kth Adams operator to the irrep (iweight).
    """

    longest_Weyl_word = [j for i in range(N-2,-1,-1) for j in range(i+1)]

    def v_decomp(dweight):
        poly = [[w,1] for w in _Weyl_orbit(dweight, N, simple_roots)]
        for i in range(len(longest_Weyl_word)):
            for j in range(len(poly)):
                if poly[j][1] != 0:
                    letter = longest_Weyl_word[i]
                    if poly[j][0][letter] >= 0:
                        continue
                    elif poly[j][0][letter] == -0.5:
                        poly[j][1] = 0
                    elif poly[j][0][letter] <= -1:
                        factor = poly[j][0][letter] + 0.5
                        poly[j][1] *= -1
                        poly[j][0] = poly[j][0] - factor*simple_roots[letter]
                    else:
                        continue
                else:
                    continue
        for monomial,coeff in poly:
            if coeff == 0:
                continue
            else:
                yield _find_iweight(monomial.tolist()), coeff

    polynomial = defaultdict(int)
    for dweight,mult in dominant_zweights.items():
        scaled_dweight = [k*x for x in dweight]
        for R,coeff in v_decomp(scaled_dweight):
            polynomial[R] += coeff*mult

    return {R:num for R,num in polynomial.items() if num != 0}
