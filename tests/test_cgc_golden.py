def test_golden_table_exists_for_current_version() -> None:
    """Every CGC_CACHE_VERSION needs pinned values."""
    assert CGC_CACHE_VERSION in GOLDEN


@pytest.mark.parametrize(
    "case", GOLDEN.get(CGC_CACHE_VERSION, []), ids=lambda case: case.label
)
def test_golden_values_match(case: GoldenCase) -> None:
    """Computed coefficients equal the pinned ones to within GOLDEN_TOL.

    A product state missing from one side counts as a zero coefficient there,
    since pyclebsch omits coefficients below cgc.EPS.
    """
    computed = cgc.calc_cgcs(list(case.product), case.sum_irrep, case.mult_idx, case.sum_state)
    product_states = case.coefficients.keys() | computed.keys()
    differences = {
        state: abs(case.coefficients.get(state, 0.0) - computed.get(state, 0.0))
        for state in product_states
    }
    worst_state = max(differences, key=differences.get)
    assert differences[worst_state] <= GOLDEN_TOL, (
        f"{case.label}: coefficient of product state {worst_state} differs by "
        f"{differences[worst_state]:.3g} from the value pinned for "
        f"CGC_CACHE_VERSION {CGC_CACHE_VERSION}"
    )

