"""Golden values that pin pyclebsch's CGC conventions.

Cached CGC tables are only valid while the conventions that produced them are
unchanged: the ordering of Gelfand-Tsetlin patterns, the labeling of
multiplicity copies, the phase convention, and the normalization rules. These
tests pin literal coefficients for a few small cases that exercise each of
those conventions, keyed by pyclebsch.cache.CGC_CACHE_VERSION.

If test_golden_values_match fails, either a bug was introduced or a
convention was changed on purpose. For an intentional change:
  1. bump CGC_CACHE_VERSION in pyclebsch/cache.py, which invalidates every
     table cached under the old conventions;
  2. add GOLDEN[<new version>] with values generated by the new code.
Never edit the values of an existing version.

A similar test name test_cache_format_version_match
exists checking the format of the metadata envelope accompanying the CGC
data in an on-disk cache. When that test fails:
  1. bump CACHE_FORMAT_VERSION in pyclebsch/cache.py, which invalidates
     every table cached using the old metadata format envelope.
  2. add ENVELOPE[<new version>] with the new versions expected keys/types.
Never edit the values of an existing version.
"""
from __future__ import annotations

from dataclasses import dataclass

import pytest

import pyclebsch.cgc as cgc
from pyclebsch.cache import CGC_CACHE_VERSION, ProductState, CGCTable
from pyclebsch.su_n_operators import IrrepWeight

# Largest allowed difference between a pinned and a computed coefficient. It
# equals cgc.EPS, the scale below which pyclebsch treats a coefficient as zero.
# Floating-point noise on these small cases is ~1e-15, while a convention
# change moves coefficients by O(0.1-1), so the margin is wide either way.
GOLDEN_TOL: float = 1e-10

# SU(3) irreps as i-weights.
FUND: IrrepWeight = (1, 0, 0)       # 3
ANTIFUND: IrrepWeight = (1, 1, 0)   # 3-bar
ADJOINT: IrrepWeight = (2, 1, 0)    # 8
TRIVIAL: IrrepWeight = (0, 0, 0)    # 1


@dataclass(frozen=True)
class GoldenCase:
    """The CGCs of one sum-irrep state, as returned by
    calc_cgcs(product, sum_irrep, mult_idx, sum_state)."""
    label: str
    product: tuple[IrrepWeight, ...]
    sum_irrep: IrrepWeight
    mult_idx: int
    sum_state: int
    coefficients: dict[ProductState, float]


